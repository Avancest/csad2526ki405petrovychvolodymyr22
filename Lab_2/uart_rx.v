module uart_rx (
    input  wire clk,        // ???????? ?????? ???????
    input  wire rst,        // ?????? ???????? (???????? ?????? 1)
    input  wire rx,         // ?????? ????? ??????? (RX)
    input  wire baud_tick,  // ???????? ??????? ????????? ???????? (baud rate)
    output reg [7:0] data_out, // ???????? 8-????? ????
    output reg ready           // ??????, ?? ???? ?????? ?? ??????????
);

    // --------------------------------------------------------
    // ???? ?????? ???????? ??????? (Finite State Machine)
    // --------------------------------------------------------
    reg [2:0] state;

    localparam IDLE  = 3'd0;  // ?????????? ?????????? ????
    localparam START = 3'd1;  // ????????? ?????????? ????
    localparam DATA  = 3'd2;  // ?????? 8 ????? ?????
    localparam STOP  = 3'd3;  // ?????????? ????-????

    initial state = IDLE;     // ?????????? ???? ? ?????????? ???????

    // --------------------------------------------------------
    // ????????? ????????
    // --------------------------------------------------------
    reg [3:0] bit_index = 0;  // ????????? ????????? ????? (0?7)
    reg [7:0] rx_shift = 0;   // ??????? ??? ??????????? ?????????? ????????? ?????
    reg [15:0] baud_count = 0; // ????????? ??? ??????????? ???? baud_tick

    // --------------------------------------------------------
    // ???????? ?????? ??????? (????????? ???????? ????????)
    // --------------------------------------------------------
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            // ???????? ???? ???????? ? ?????????? ????
            state <= IDLE;
            bit_index <= 0;
            rx_shift <= 0;
            baud_count <= 0;
            ready <= 0;
            data_out <= 0;
        end else begin
            // ?? ????????????? ?????????? = 0
            ready <= 0;

            // ?????? ?????? ???????? UART
            case (state)

                // ------------------------------------------------
                // ???? IDLE: ????????, ???? RX ????? 0 (?????-???)
                // ------------------------------------------------
                IDLE: begin
                    if (!rx) begin             // ???????? ???? ?? RX (??????? ?????)
                        state <= START;        // ?????????? ?? ????????? ?????????? ????
                        baud_count <= 0;       // ????????? ????????? ??????
                    end
                end

                // ------------------------------------------------
                // ???? START: ???????? ???????? ?????????? ????
                // ------------------------------------------------
                START: begin
                    if (baud_tick) baud_count <= baud_count + 1;

                    // ???? ?????? ???????? ??????? ?????????? ????,
                    // ?????? ???????? ???????????, ?? ?? ??????? ?????
                    if (baud_count == 1) begin
                        baud_count <= 0;
                        bit_index <= 0;
                        state <= DATA;         // ????????? ?????? ?????
                    end
                end

                // ------------------------------------------------
                // ???? DATA: ?????????? ???????? 8 ????? ?????
                // ------------------------------------------------
                DATA: begin
                    if (baud_tick) begin
                        rx_shift[bit_index] <= rx; // ?????????? ???????? ???
                        bit_index <= bit_index + 1;
                        
                        // ????? ????????? 8 ????? ?????????? ?? ????-????
                        if (bit_index == 7)
                            state <= STOP;
                    end
                end

                // ------------------------------------------------
                // ???? STOP: ??????????? ????-??? ? ?????????? ??????
                // ------------------------------------------------
                STOP: begin
                    if (baud_tick) begin
                        data_out <= rx_shift;  // ?????????? ???????? ????
                        ready <= 1;            // ????????????, ?? ???? ??????
                        state <= IDLE;         // ???????????? ?? ?????????? ?????? ?????
                    end
                end
            endcase
        end
    end
endmodule

