module uart_tx (
    input  wire clk,           // ???????? ??????
    input  wire rst,           // ?????? ???????? (???????? ?? ????? 1)
    input  wire [7:0] data_in, // ?????? ???? ??? ????????
    input  wire start,         // ?????? ??????? ????????
    input  wire baud_tick,     // ??????? ?????????? ???????? (??????? = ????????? ????????)
    output reg  tx,            // ???????? ????????????? ?????? (TX)
    output reg  busy           // ??????, ?? ???????? ??????
);

    // --------------------------------------------------------
    // ???????? ???????????? ?????
    // --------------------------------------------------------
    reg [9:0] shift_reg = 10'b1111111111; // ??????? ???????: [STOP][DATA(8)][START]
    reg [3:0] bit_index = 0;              // ????????? ????????? ????? (0?9)

    // --------------------------------------------------------
    // ???????? ?????? ???????? (????????? ???????? ????????)
    // --------------------------------------------------------
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            // ???????? ???? ???????? ? ?????????? ????
            tx <= 1'b1;                   // ????? TX ? ????? ?????? (???. 1)
            busy <= 0;                    // ????????? ?? ????????
            bit_index <= 0;               // ??????? ???????
            shift_reg <= 10'b1111111111;  // ??????? ???????? (??? ???? 1)
        end else begin
            // ------------------------------------------------
            // ?????? ????????: ??? start=1 ? ???? ????????? ???????
            // ------------------------------------------------
            if (start && !busy) begin
                // ???????? ????: [STOP=1][DATA][START=0]
                shift_reg <= {1'b1, data_in, 1'b0};
                busy <= 1;                 // ????????? ????????
                bit_index <= 0;            // ????????? ? ??????? ????
            end 
            // ------------------------------------------------
            // ???????? ????? ?? ?????? ???? ?? ????? baud_tick
            // ------------------------------------------------
            else if (busy && baud_tick) begin
                tx <= shift_reg[bit_index]; // ???????? ???????? ??? ?? ????? TX
                bit_index <= bit_index + 1; // ?????????? ?? ?????????? ????

                // ????? ???????? ???? 10 ????? ?????????? ??????
                if (bit_index == 9)
                    busy <= 0;             // ??????? ?? ????? ????????
            end
        end
    end
endmodule
